Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Phones stay portrait-locked; tablets/iPads (shortestSide ≥ 600dp) are freed
  // to rotate so the wide two-pane / NavigationRail layouts can engage.
  //
  // MUST be crash-proof: at cold start on real devices the platform view list
  // can still be empty, so `.views.first` throws StateError. An uncaught throw
  // here aborts main() before runApp() → the app never renders a frame (users
  // just see a dark screen). So we guard it and default to the safe portrait
  // lock; the app itself still switches to wide layouts at runtime via
  // MediaQuery, this only decides whether rotation is *allowed*.
  try {
    final views = WidgetsBinding.instance.platformDispatcher.views;
    final view = views.isNotEmpty ? views.first : null;
    final dpr = view?.devicePixelRatio ?? 0;
    final shortestSide = (view != null && dpr > 0)
        ? (view.physicalSize / dpr).shortestSide
        : 0.0;
    if (shortestSide >= 600) {
      await SystemChrome.setPreferredOrientations(DeviceOrientation.values);
    } else {
      await SystemChrome.setPreferredOrientations([
        DeviceOrientation.portraitUp,
        DeviceOrientation.portraitDown,
      ]);
    }
  } catch (e) {
    debugPrint('[startup] orientation setup skipped: $e');
    await SystemChrome.setPreferredOrientations([
      DeviceOrientation.portraitUp,
      DeviceOrientation.portraitDown,
    ]);
  }
  SystemChrome.setSystemUIOverlayStyle(
    const SystemUiOverlayStyle(
      statusBarColor: Colors.transparent,
      statusBarIconBrightness: Brightness.dark,
    ),
  );

  // Firebase + push BEFORE we touch anything else
  await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform);
  await _initLocalNotifications();

  await ApiService().initialize();
  await AppSettings().load();
  await TranslationService.I.init();

  final hasSession = await AuthService.instance.isLoggedIn;

  // Render the UI IMMEDIATELY. Everything below does network / APNs / FCM work
  // and is NOT needed to draw the first frame. Awaiting any of it before
  // runApp() risks a blank screen on launch: their try/catch blocks guard
  // THROWN errors, not a stalled request, so a slow/unreachable backend (or an
  // FCM topic-subscribe that never returns) would hang main() forever and
  // runApp() would never run. So we defer ALL of it to after the first frame.
  runApp(const TCSApp());

  // Post-frame, fully non-blocking push + session bootstrap.
  unawaited(() async {
    try {
      await _initFcm();
    } catch (e, st) {
      debugPrint('[FCM] init failed (continuing without push): $e\n$st');
    }
    if (hasSession) {
      unawaited(NotificationService.instance.bootstrap());
      unawaited(registerFcmToken());
    }
  }());
}

