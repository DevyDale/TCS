final FlutterLocalNotificationsPlugin localNotifications =
    FlutterLocalNotificationsPlugin();

const AndroidNotificationChannel _channelAll = AndroidNotificationChannel(
  'tcs_all', 'All Notifications',
  description: 'Default channel for TCS',
  importance: Importance.high,
);
const AndroidNotificationChannel _channelAnn = AndroidNotificationChannel(
  'tcs_announcements', 'Announcements',
  description: 'Campus-wide announcements',
  importance: Importance.high,
);
const AndroidNotificationChannel _channelGroup = AndroidNotificationChannel(
  'tcs_group_activity', 'Group Activity',
  description: 'New posts in your groups',
  importance: Importance.defaultImportance,
);

// Top-level (or static) — required for FCM to invoke when app is killed
@pragma('vm:entry-point')
Future<void> _firebaseMessagingBackgroundHandler(RemoteMessage message) async {
  await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform);
  // FCM "notification" payloads auto-display via the system tray when the
  // app is in background/killed, so this handler is a no-op for those.
  // Add custom logic here if you ever send data-only payloads.
}

Future<void> _initLocalNotifications() async {
  const androidInit = AndroidInitializationSettings('@mipmap/ic_launcher');
  const iosInit = DarwinInitializationSettings(
    requestAlertPermission: false,
    requestBadgePermission: false,
    requestSoundPermission: false,
  );
  await localNotifications.initialize(
    settings: const InitializationSettings(android: androidInit, iOS: iosInit),
  );
  final android = localNotifications
      .resolvePlatformSpecificImplementation<AndroidFlutterLocalNotificationsPlugin>();
  await android?.createNotificationChannel(_channelAll);
  await android?.createNotificationChannel(_channelAnn);
  await android?.createNotificationChannel(_channelGroup);
}

Future<void> _initFcm() async {
  // Background handler MUST be registered before any other listeners
  FirebaseMessaging.onBackgroundMessage(_firebaseMessagingBackgroundHandler);

  // Foreground messages: FCM does NOT show these automatically — render
  // them ourselves via flutter_local_notifications
  FirebaseMessaging.onMessage.listen((RemoteMessage msg) {
    final n = msg.notification;
    if (n == null) return;
    final ch = _pickChannel(msg);
    localNotifications.show(
      id: msg.hashCode,
      title: n.title,
      body: n.body,
      notificationDetails: NotificationDetails(
        android: AndroidNotificationDetails(
          ch.id, ch.name,
          channelDescription: ch.description,
          importance: ch.importance,
          icon: '@mipmap/ic_launcher',
        ),
        iOS: const DarwinNotificationDetails(),
      ),
    );
  });

  // Re-register the device token with the backend whenever FCM rotates it.
  FirebaseMessaging.instance.onTokenRefresh.listen((token) async {
    try { await ApiService().updateFcmToken(token); } catch (_) {}
  });

  // Deep-link announcement push taps → Noticeboard.
  // • App in background: route immediately (GetMaterialApp is mounted).
  // • App launched from terminated state: stash the id; the splash opens the
  //   board once it has routed to the dashboard (avoids a navigation race).
  FirebaseMessaging.onMessageOpenedApp.listen((msg) => _routeAnnouncement(msg.data));
  final initialMsg = await FirebaseMessaging.instance.getInitialMessage();
  if (initialMsg != null && initialMsg.data['type'] == 'announcement') {
    pendingAnnouncementId = (initialMsg.data['announcement_id'] ?? '').toString();
  }

  await syncFcmTopics(); // honor saved user prefs on cold start
}

/// Routes an FCM data payload to the Noticeboard when it is an announcement.
/// Used for the background-tap (onMessageOpenedApp) path while the app runs.
void _routeAnnouncement(Map<String, dynamic> data) {
  if (data['type'] != 'announcement') return;
  final id = (data['announcement_id'] ?? '').toString();
  Get.to(() => NoticeboardScreen(highlightId: id.isEmpty ? null : id));
}

/// Registers THIS device's FCM token with the backend (POST
/// /users/me/fcm-token/) so the server can push to user.fcm_token.
/// Must run while authenticated. Safe to call repeatedly.
Future<void> registerFcmToken() async {
  final fcm = FirebaseMessaging.instance;
  try {
    await fcm.requestPermission(alert: true, badge: true, sound: true);
    if (Platform.isIOS) {
      // APNs delivers its token asynchronously after registration; poll
      // briefly so getToken() doesn't throw apns-token-not-set on first launch.
      String? apns = await fcm.getAPNSToken();
      for (var i = 0; i < 10 && apns == null; i++) {
        await Future.delayed(const Duration(seconds: 1));
        apns = await fcm.getAPNSToken();
      }
      if (apns == null) {
        debugPrint('[FCM] APNs token not ready yet - onTokenRefresh will register later');
        return;
      }
    }
    final token = await fcm.getToken();
    if (token != null && token.isNotEmpty) {
      await ApiService().updateFcmToken(token);
      debugPrint('[FCM] device token registered with backend');
    }
  } catch (e) {
    debugPrint('[FCM] token registration failed: ' + e.toString());
  }
}

AndroidNotificationChannel _pickChannel(RemoteMessage msg) {
  final type = msg.data['type'];
  if (type == 'announcement')   return _channelAnn;
  if (type == 'group_activity') return _channelGroup;
  return _channelAll;
}

/// Re-subscribe / unsubscribe from FCM topics based on the user's saved
/// preferences. Call this from settings_screen.dart whenever a notification
/// toggle changes — it guarantees the user actually controls delivery.
Future<void> syncFcmTopics() async {
  final s = AppSettings();
  final fcm = FirebaseMessaging.instance;

  // ← FIX: On iOS, subscribeToTopic requires an APNS token. The iOS Simulator
  // never gets one (Apple limitation), and even on real devices it can take a
  // moment after launch. Skip topic sync gracefully if APNS isn't ready.
  if (Platform.isIOS) {
    try {
      final apnsToken = await fcm.getAPNSToken();
      if (apnsToken == null) {
        debugPrint(
            '[FCM] No APNS token yet (likely simulator) — skipping topic sync');
        return;
      }
    } catch (e) {
      debugPrint('[FCM] APNS check failed: $e — skipping topic sync');
      return;
    }
  }

  // ← FIX: Wrap the actual subscribe/unsubscribe calls so a transient
  // network or token issue can't crash the app.
  try {
    if (s.pushEnabled) {
      await fcm.subscribeToTopic('all_users');
      s.announcements
          ? await fcm.subscribeToTopic('announcements')
          : await fcm.unsubscribeFromTopic('announcements');
      s.groupActivity
          ? await fcm.subscribeToTopic('group_activity')
          : await fcm.unsubscribeFromTopic('group_activity');
    } else {
      await fcm.unsubscribeFromTopic('all_users');
      await fcm.unsubscribeFromTopic('announcements');
      await fcm.unsubscribeFromTopic('group_activity');
    }
  } catch (e) {
    debugPrint('[FCM] Topic sync failed: $e');
  }
}

