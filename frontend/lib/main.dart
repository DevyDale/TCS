class _TCSAppState extends State<TCSApp> {
  final _settings = AppSettings();

  @override
  void initState() {
    super.initState();
    _settings.addListener(_rebuild);
  }

  @override
  void dispose() {
    _settings.removeListener(_rebuild);
    super.dispose();
  }

  void _rebuild() {
    if (!mounted) return;
    // Rebuild MaterialApp itself (theme/locale swap)...
    setState(() {});
    // ...then force EVERY element in the tree — including pages already pushed
    // on the Navigator and const subtrees — to rebuild. AppC reads
    // AppSettings().isDark directly rather than via an InheritedWidget, so a
    // plain setState only repaints this widget; cached route pages would keep
    // the old theme until popped/re-pushed (the "not all pages change" bug).
    // forceAppUpdate walks the whole element tree and marks each dirty.
    Get.forceAppUpdate();
  }

  // Cold start can't reliably read the device size before runApp() (the view
  // list may be empty), so main() defaults to a safe portrait lock. Once the
  // first frame has a valid MediaQuery we upgrade tablets/iPads to allow
  // rotation. Runs once. Never touches phones (they stay portrait).
  bool _orientationRefined = false;
  void _refineOrientation(BuildContext context) {
    if (_orientationRefined) return;
    final shortest = MediaQuery.maybeOf(context)?.size.shortestSide ?? 0;
    if (shortest <= 0) return; // metrics not ready yet — try again next frame
    _orientationRefined = true;
    if (shortest >= 600) {
      SystemChrome.setPreferredOrientations(DeviceOrientation.values);
    }
  }

